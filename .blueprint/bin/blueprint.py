def shq(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("`", "\\`") + '"'


def agenticteam_tasks(plan, comp, team=None):
    writable = None
    if team is not None:
        writable = {a["id"] for a in team.get("agents", []) if a.get("access") in WRITE_ACCESS}
    tasks, by_phase = [], {}
    group_of = {}
    for ph in plan["phases"]:
        owners = sorted({r["owner"] for r in comp["rows"] if r["phase"] == ph["id"] and r["status"] != "verified"} |
                        {p["owner"] for p in comp["patterns"] if p["phase"] == ph["id"]} - {None})
        for o in owners:
            tid = f"bp-{ph['id']}-{o}".lower()
            for r in comp["rows"]:
                if r["phase"] == ph["id"] and r["owner"] == o:
                    group_of[r["path"]] = tid
    prev_ids = []
    for ph in plan["phases"]:
        ids_this = []
        owners = sorted({r["owner"] for r in comp["rows"] if r["phase"] == ph["id"] and r["status"] != "verified"} |
                        {p["owner"] for p in comp["patterns"] if p["phase"] == ph["id"]} - {None})
        for o in owners:
            tid = f"bp-{ph['id']}-{o}".lower()
            files = [r for r in comp["rows"] if r["phase"] == ph["id"] and r["owner"] == o and r["status"] != "verified"]
            pats = [p for p in comp["patterns"] if p["phase"] == ph["id"] and p["owner"] == o]
            deps = set(prev_ids)
            for r in files:
                for d in r["dependsOn"]:
                    g = group_of.get(d)
                    if g and g != tid:
                        deps.add(g)
            checks = sorted({r["verify"] for r in files if r["verify"]} | {p["verify"] for p in pats if p["verify"]})
            tasks.append({
                "id": tid, "owner": o, "stage": "04_build", "phase": ph["id"], "action": "build", "target": "local",
                "title": f"{ph['id']} {ph.get('name', '')}: {o} builds {len(files)} file(s)" + (f" and {len(pats)} pattern(s)" if pats else ""),
                "paths": [r["path"] for r in files] + [p["glob"] for p in pats],
                "dependsOn": sorted(deps),
                "inputs": [".blueprint/STRUCTURE.md", ".blueprint/ROSTER.md"],
                "acceptance": [f"Every listed file exists, matches its purpose in .blueprint/STRUCTURE.md, and is marked built",
                               f"Phase exit: {ph.get('exit') or ph.get('goal') or ph['id']}"],
                "checks": checks,
                "writable": None if writable is None else (o in writable),
            })
            ids_this.append(tid)
        if ids_this:
            tasks.append({"id": f"bp-{ph['id']}-verify".lower(), "owner": "qa-lead", "stage": "04_build", "phase": ph["id"],
                          "action": "test", "target": "local",
                          "title": f"{ph['id']} {ph.get('name', '')}: verify the phase", "paths": [], "dependsOn": ids_this,
                          "inputs": [".blueprint/STRUCTURE.md"], "verifies": ids_this,
                          "acceptance": [f"python .blueprint/bin/blueprint.py verify --phase {ph['id']} --run passes"],
                          "checks": [f"python .blueprint/bin/blueprint.py verify --phase {ph['id']} --run"], "writable": None})
            prev_ids = ids_this + [f"bp-{ph['id']}-verify".lower()]
    return tasks


def cmd_export(args):
    root = find_root(args.root)
    plan = load_plan(root)
    state = load_state(root)
    comp = compute(root, plan, state)
    fmt = args.format
    if fmt == "codeowners":
        gh = {r["id"]: r.get("github") for r in plan["roster"]}
        print("# Generated from .blueprint/blueprint.json owner rules (last match wins).")
        for rule in plan["owners"]:
            handle = gh.get(rule["owner"])
            pat = rule["pattern"] if rule["pattern"].startswith(("/", "*")) else "/" + rule["pattern"]
            if handle:
                print(f"{pat} {handle}")
            else:
                print(f"# {pat} {rule['owner']}  (agent or no GitHub handle in roster)")
    elif fmt == "csv":
        wr = csv.writer(sys.stdout, lineterminator="\n")
        wr.writerow(["kind", "path", "action", "module", "phase", "owner", "status", "contract", "purpose", "verify"])
        for r in comp["rows"]:
            wr.writerow(["file", r["path"], r["action"], r["module"], r["phase"], r["owner"], r["status"], r["contract"], r["purpose"], r["verify"]])
        for p in comp["patterns"]:
            wr.writerow(["pattern", p["glob"], "create", p["module"], p["phase"], p["owner"], f"{len(p['instances'])} on disk", False, p["purpose"], p["verify"]])
    elif fmt == "json":
        print(json.dumps({"app": plan["app"], "phases": plan["phases"], "roster": plan["roster"], "rows": comp["rows"],
                          "patterns": comp["patterns"], "unplanned": state.get("unplanned", []), "syncedAt": state.get("syncedAt"),
                          "data": data_view(plan, state)},
                         indent=2, ensure_ascii=False))
    elif fmt == "agenticteam":
        team = read_json(Path(args.team)) if args.team else None
        tasks = agenticteam_tasks(plan, comp, team)
        bad = [t for t in tasks if t.get("writable") is False]
        if bad:
            for t in bad:
                print(f"error: {t['owner']} cannot write files in AgenticTeam (access is not workspace-write): {t['id']}", file=sys.stderr)
            sys.exit(1)
        if args.json:
            print(json.dumps(tasks, indent=2, ensure_ascii=False))
            return
        cli = "python .agentic-team/bin/agentic_team.py"
        print("# AgenticTeam build tasks generated from the app blueprint. Review, then run in order.")
        for t in tasks:
            parts = [cli, "add-task", "--project .", "--id", t["id"], "--title", shq(t["title"]), "--owner", t["owner"], "--stage", t["stage"],
                     "--action", t["action"], "--target", t["target"]]
            parts += [x for p in t["paths"] for x in ("--path", shq(p))]
            parts += [x for d in t["dependsOn"] for x in ("--depends-on", d)]
            parts += [x for i in t["inputs"] for x in ("--input", i)]
            parts += [x for a in t["acceptance"] for x in ("--acceptance", shq(a))]
            parts += [x for c in t["checks"] for x in ("--check", shq(c))]
            parts += [x for v in t.get("verifies", []) for x in ("--verifies", v)]
            print(" ".join(parts))
    else:
        die(f"unknown format {fmt}", 64)


