def cmd_verify(args):
    root = find_root(args.root)
    plan = load_plan(root)
    groups = {}
    for f in plan["files"]:
        if f.get("action") == "delete" or (args.phase and f.get("phase") != args.phase):
            continue
        if args.owner and owner_of(plan, f["path"])[0] != args.owner:
            continue
        cmd = item_verify(plan, f)
        if cmd:
            groups.setdefault(cmd, []).append(f["path"])
    if not groups:
        print("No verify commands in scope.")
        return
    if not args.run:
        print("Verify commands (add --run to execute them; each passing command marks its present files verified):")
        for cmd, paths in groups.items():
            print(f"  {cmd}    # {len(paths)} file(s)")
        return
    state = load_state(root)
    failed = 0
    for cmd, paths in groups.items():
        print(f"$ {cmd}")
        try:
            res = subprocess.run(cmd, shell=True, cwd=root, timeout=args.timeout)
            ok = res.returncode == 0
        except subprocess.TimeoutExpired:
            ok = False
            print(f"  timed out after {args.timeout}s")
        print(f"  {'passed' if ok else 'FAILED'} for {len(paths)} file(s)")
        failed += 0 if ok else 1
        for p in paths:
            fp = root / p
            rec = state["files"].setdefault(p, {})
            if fp.is_file():
                rec["verified"] = {"ok": ok, "cmd": cmd, "at": now_iso(), "sha": file_sha(fp) if ok else None}
        append_log(root, {"event": "verify", "cmd": cmd, "ok": ok, "files": len(paths)})
    save_state(root, state)
    render_all(root, plan, state, quiet=True)
    sys.exit(1 if failed else 0)


